import assert from 'node:assert/strict';
import { chromium } from 'playwright';

const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
try {
  await page.goto(new URL('?editor', process.env.APP_URL || 'http://localhost:5173/').href);
  await page.locator('#toolbar').waitFor();
  await page.locator('[data-tool="hand"]').click();
  assert.equal(await page.evaluate(() => designer.store.ui.tool), 'hand');
  const viewport = await page.locator('#viewport').boundingBox();
  const before = await page.evaluate(() => designer.canvas.getView());
  await page.mouse.move(viewport.x + 150, viewport.y + 150);
  await page.mouse.down();
  await page.mouse.move(viewport.x + 210, viewport.y + 180, { steps: 5 });
  await page.mouse.up();
  const after = await page.evaluate(() => designer.canvas.getView());
  assert.ok(Math.abs(after.x - before.x - 60) < 2);
  console.log('PASS ferramenta Mão visível move o canvas');
  await page.evaluate(() => { if (!designer.store.ui.showRulers) designer.store.toggleRulers(); });
  await page.getByRole('button', { name: 'Gerenciar guias', exact: true }).click();
  await page.getByLabel('Posição da nova guia em px').fill('-120');
  await page.getByRole('button', { name: 'Adicionar', exact: true }).click();
  await page.getByLabel('Posição da guia 1 em px').fill('64');
  await page.getByLabel('Posição da guia 1 em px').press('Enter');
  assert.equal(await page.evaluate(() => designer.store.page().guides[0].pos), 64);
  await page.getByRole('button', { name: 'Remover guia 1', exact: true }).click();
  assert.equal(await page.evaluate(() => designer.store.page().guides.length), 0);
  await page.keyboard.press('Escape');
  await page.keyboard.press('Control+z');
  assert.equal(await page.evaluate(() => designer.store.page().guides[0].pos), 64);
  console.log('PASS posições exatas e remoção de guias têm histórico de desfazer');
  const ruler = await page.locator('.ruler-top').boundingBox();
  await page.mouse.move(ruler.x + 100, ruler.y + 10);
  await page.mouse.down();
  await page.mouse.move(ruler.x + 100, ruler.y + 150);
  await page.keyboard.press('Escape');
  await page.mouse.up();
  assert.equal(await page.evaluate(() => designer.store.page().guides.length), 1);
  assert.equal(await page.evaluate(() => designer.store.ui.guideDrag), null);
  await page.mouse.move(ruler.x + 100, ruler.y + 10);
  await page.mouse.down();
  await page.mouse.move(ruler.x + ruler.width + 30, ruler.y + 150);
  await page.mouse.up();
  assert.equal(await page.evaluate(() => designer.store.page().guides.length), 1);
  console.log('PASS Escape e soltar fora do canvas cancelam a criação de guia');
  const id = await page.evaluate(async () => {
    const { createNode } = await import('/src/model.js');
    const node = createNode('frame', { w: 400, h: 300 });
    node.layout.mode = 'grid';
    node.layout.colsTemplate = '100px 1fr';
    designer.store.update((p) => p.children.push(node), { commit: true });
    designer.store.setSelection([node.id]);
    return node.id;
  });
  const cols = page.getByRole('textbox', { name: 'grid-template-columns', exact: true });
  await page.getByRole('button', { name: 'Gerenciar guias', exact: true }).click();
  await page.getByRole('button', { name: 'Remover todas', exact: true }).click();
  await page.getByRole('button', { name: 'Bordas da seleção', exact: true }).click();
  await page.getByRole('button', { name: 'Centro da seleção', exact: true }).click();
  await page.getByRole('button', { name: 'Bordas da seleção', exact: true }).click();
  assert.equal(await page.evaluate(() => designer.store.page().guides.length), 6);
  await page.getByLabel('Travar guias no canvas', { exact: true }).press('Space');
  await page.keyboard.press('Escape');
  assert.equal(await page.evaluate(() => designer.store.ui.guidesLocked), true);
  assert.equal(await page.locator('.guide-line:not(.drag)').evaluateAll((elements) => elements.every((el) => getComputedStyle(el).pointerEvents === 'none')), true);
  assert.equal(await page.evaluate(() => localStorage.getItem('pd.guidesLocked')), '1');
  await page.keyboard.press('Control+z');
  assert.equal(await page.evaluate(() => designer.store.page().guides.length), 4);
  console.log('PASS bordas e centro geram guias sem duplicar; trava impede arrasto e a criação conjunta desfaz em um passo');
  await cols.fill('minmax(');
  assert.equal(await cols.getAttribute('aria-invalid'), 'true');
  assert.equal(await page.evaluate((id) => designer.store.get(id).layout.colsTemplate, id), '100px 1fr');
  await cols.press('Escape');
  assert.equal(await cols.inputValue(), '100px 1fr');
  await cols.fill('repeat(3, minmax(0, 1fr))');
  await cols.press('Enter');
  assert.equal(await page.evaluate((id) => designer.canvas.els.get(id).style.gridTemplateColumns, id), 'repeat(3, minmax(0px, 1fr))');
  await page.getByRole('tab', { name: 'Código', exact: true }).click();
  await page.getByLabel('Quebrar linhas', { exact: true }).press('Space');
  assert.equal(await page.locator('.code-view').evaluate((el) => getComputedStyle(el).whiteSpace), 'pre-wrap');
  console.log('PASS CSS inválido preserva layout, Escape restaura e código permite quebra de linhas');
  for (const width of [1440, 1140, 1000, 900]) {
    await page.setViewportSize({ width, height: 900 });
    await page.waitForTimeout(100);
    const fits = await page.evaluate(() => {
      const s = document.querySelector('.stage').getBoundingClientRect();
      const t = document.querySelector('.toolbar').getBoundingClientRect();
      const z = document.querySelector('.zoom-widget').getBoundingClientRect();
      return t.left >= s.left && t.right <= s.right && !(t.left < z.right && t.right > z.left && t.top < z.bottom && t.bottom > z.top);
    });
    assert.ok(fits, `Ferramentas e zoom devem caber em ${width}px`);
  }
  assert.deepEqual(errors, []);
  console.log('PASS barra agrupada cabe no palco sem cobrir zoom (900–1440px) e sem erros');
} finally { await browser.close(); }
